package util;

import java.util.Locale;

/**
 * Command line helper that prints password hashes for seeding the database.
 *
 * <p>Run it with no arguments to print a ready-to-paste SQL script for the
 * demo accounts, or pass a password to hash it:
 *
 * <pre>{@code
 * java -cp ".;lib/*" util.PasswordHashTool
 * java -cp ".;lib/*" util.PasswordHashTool "MySecret"
 * }</pre>
 *
 * <p>The generated values use the same PBKDF2-HMAC-SHA256 format that
 * {@link PasswordUtil#hash(String)} produces, so the application verifies them
 * normally. Because the salt is random, re-running the tool produces a
 * different (equally valid) hash every time.
 */
public final class PasswordHashTool {

    private PasswordHashTool() {
        // Utility class - not instantiable.
    }

    /**
     * Entry point.
     *
     * @param args optionally, one password to hash
     */
    public static void main(String[] args) {
        if (args.length == 0) {
            printSeedScript();
            return;
        }
        System.out.println(PasswordUtil.hash(args[0]));
    }

    /**
     * Prints SQL that sets the demo accounts to PBKDF2 hashes.
     *
     * <p>The demo passwords are {@code manager123} for the manager and
     * {@code emp123} for the three employees - the same credentials the
     * README documents.
     */
    private static void printSeedScript() {
        String managerHash = PasswordUtil.hash("manager123");
        String employeeHash = PasswordUtil.hash("emp123");
        System.out.println("-- Generated by util.PasswordHashTool on " + java.time.LocalDateTime.now());
        System.out.println("USE employee_performance_db;");
        System.out.println();
        System.out.println("UPDATE users SET password = '" + managerHash + "'");
        System.out.println(" WHERE email = 'manager@company.com';");
        System.out.println();
        System.out.println("UPDATE users SET password = '" + employeeHash + "'");
        System.out.println(" WHERE email IN ('priya@company.com', 'amit@company.com', 'sneha@company.com');");
        System.out.println();
        System.out.println(String.format(Locale.ROOT,
                "-- manager123 -> %s%n-- emp123     -> %s", managerHash, employeeHash));
    }
}
